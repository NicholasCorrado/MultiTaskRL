"""Online estimation of the per-task normalized return gap used by DRATS.

This implements lines 8-10 of Algorithm 1 in "Distributionally Robust Multi-Task
Reinforcement Learning via Adaptive Task Sampling":

    g_i = clip( (J_ref_i - J_hat_i) / (J_ref_i - J_rand_i),  0, 1 )

where
    J_hat_i   Monte Carlo estimate of the current policy's return on task i,
    J_ref_i   reference (target) return on task i,
    J_rand_i  return of a random policy on task i, used only to normalize gaps
              so that tasks with different return scales are comparable.

Reference returns follow the paper: they are initialized to a known upper bound
(e.g. r_max * H_max) and are latched to the *maximum observed return* on a task
once that task's success rate exceeds `ref_success_threshold`. When no upper
bound is available (e.g. MuJoCo, where tasks have no notion of success), pass
`return_ref_init=None` and the maximum observed return is used throughout.

The estimator is shared by the on-policy (PPO) and off-policy (DDPG/TD3)
experiment scripts so that every algorithm prioritizes tasks with exactly the
same statistic.

Off-policy note: with DDPG/TD3 the episodes fed to `record_episode` are
generated by the *behavior* policy (i.e. with exploration noise), so J_hat is a
slightly pessimistic estimate of the current greedy policy's return. This is
intentional -- it keeps the estimate free (no extra rollouts) and it biases all
task-sampling methods identically.
"""

from collections import deque
from typing import List, Optional, Sequence, Union

import numpy as np


def _as_per_task_array(value, num_tasks: int, name: str) -> Optional[np.ndarray]:
    """Broadcast a scalar / sequence into a length-`num_tasks` float array."""
    if value is None:
        return None
    arr = np.asarray(value, dtype=np.float64).reshape(-1)
    if arr.size == 1:
        arr = np.repeat(arr, num_tasks)
    if arr.size != num_tasks:
        raise ValueError(
            f"{name} must be a scalar or have one entry per task, "
            f"got {arr.size} entries for {num_tasks} tasks"
        )
    return arr


class ReturnGapEstimator:
    """Tracks per-task returns, success rates, reference returns, and gaps.

    Args:
        num_tasks: number of tasks k.
        return_window: number of most recent episodes per task averaged into
            J_hat_i. Acts as a sliding-window Monte Carlo estimate.
        success_window: number of most recent episodes per task averaged into
            the success rate (used to latch reference returns, and by the
            easy/hard-first curriculum baselines).
        return_ref_init: initial reference return J_ref (scalar or per-task).
            `None` means "no known upper bound": J_ref is the maximum observed
            return from the start.
        return_rand: random-policy return J_rand (scalar or per-task). `None`
            means it is estimated online, either from episodes explicitly marked
            `random_policy=True` (an off-policy algorithm's warm-up phase) or
            from the first `rand_window` episodes of each task.
        rand_window: when J_rand is not supplied, treat the first `rand_window`
            episodes of each task as random-policy episodes. Use this for
            on-policy algorithms, which have no warm-up phase: the initial
            policy is untrained, so its return is the natural J_rand. 0 disables
            it, in which case J_rand is 0 until random-policy episodes arrive.
        ref_success_threshold: success rate above which J_ref_i switches to the
            maximum return observed on task i (paper uses 0.5).
        use_success_as_return: if True, the gap is computed on success rates
            instead of returns, i.e. J_hat = success rate, J_ref = 1, J_rand = 0.
    """

    def __init__(
        self,
        num_tasks: int,
        return_window: int = 20,
        success_window: int = 20,
        return_ref_init: Optional[Union[float, Sequence[float]]] = None,
        return_rand: Optional[Union[float, Sequence[float]]] = None,
        rand_window: int = 0,
        ref_success_threshold: float = 0.5,
        use_success_as_return: bool = False,
    ):
        self.num_tasks = int(num_tasks)
        self.use_success_as_return = bool(use_success_as_return)
        self.ref_success_threshold = float(ref_success_threshold)
        self.rand_window = int(rand_window)

        self._returns: List[deque] = [deque(maxlen=return_window) for _ in range(self.num_tasks)]
        self._successes: List[deque] = [deque(maxlen=success_window) for _ in range(self.num_tasks)]
        self._random_returns: List[List[float]] = [[] for _ in range(self.num_tasks)]

        self.return_max = np.full(self.num_tasks, -np.inf)
        self.return_ref_init = _as_per_task_array(return_ref_init, self.num_tasks, "return_ref_init")
        self.return_rand = _as_per_task_array(return_rand, self.num_tasks, "return_rand")

        # Once a task's success rate clears the threshold we permanently trust
        # the best return we have actually seen on it more than the (loose)
        # r_max * H_max upper bound.
        self.ref_is_max_observed = np.zeros(self.num_tasks, dtype=bool)
        if self.return_ref_init is None:
            self.ref_is_max_observed[:] = True

        self._returns_prev: Optional[np.ndarray] = None

    # ------------------------------------------------------------------
    # Data collection
    # ------------------------------------------------------------------

    def record_episode(
        self,
        task_id: int,
        episodic_return: float,
        success: float = 0.0,
        random_policy: bool = False,
    ) -> None:
        """Record one finished episode.

        Set `random_policy=True` for episodes collected during an off-policy
        algorithm's uniform-random warm-up phase: those are used to estimate
        J_rand and are excluded from J_hat and from the max observed return.
        The first `rand_window` episodes of each task are treated the same way.
        """
        tid = int(task_id)
        ret = float(episodic_return)
        self._successes[tid].append(float(success))

        needs_rand_estimate = self.return_rand is None
        in_rand_window = needs_rand_estimate and len(self._random_returns[tid]) < self.rand_window
        if random_policy or in_rand_window:
            self._random_returns[tid].append(ret)
            return

        self._returns[tid].append(ret)
        if ret > self.return_max[tid]:
            self.return_max[tid] = ret

    def finalize_random_returns(self) -> np.ndarray:
        """Set J_rand from the episodes collected by the random warm-up policy.

        Tasks that saw no warm-up episode fall back to the mean over the tasks
        that did; if there were no warm-up episodes at all, J_rand is 0.
        Does nothing if J_rand was supplied explicitly.
        """
        if self.return_rand is None:
            self.return_rand = self._rand()
        return self.return_rand

    def clear_returns(self) -> None:
        """Drop the buffered returns so J_hat is estimated from fresh episodes only.

        Reproduces the paper's per-iteration Monte Carlo estimate; by default we
        instead keep a sliding window, which is lower variance when a task's
        sampling probability is near the floor eps.
        """
        for d in self._returns:
            d.clear()

    # ------------------------------------------------------------------
    # Statistics
    # ------------------------------------------------------------------

    def _rand(self) -> np.ndarray:
        """J_rand: supplied, or the running mean of the random-policy episodes."""
        if self.use_success_as_return:
            # Gaps are computed on success rates, which run from 0 to 1 on every
            # task. Episode returns collected by the random policy are on a
            # completely different scale and must not be used here.
            return np.zeros(self.num_tasks, dtype=np.float64)
        if self.return_rand is not None:
            return self.return_rand

        est = np.array(
            [np.mean(v) if len(v) > 0 else np.nan for v in self._random_returns],
            dtype=np.float64,
        )
        if np.all(np.isnan(est)):
            return np.zeros(self.num_tasks, dtype=np.float64)
        # Tasks with no random-policy episode yet borrow the average of the rest.
        return np.where(np.isnan(est), np.nanmean(est), est)

    def success_rates(self) -> np.ndarray:
        return np.array(
            [float(np.mean(s)) if len(s) > 0 else 0.0 for s in self._successes],
            dtype=np.float64,
        )

    def episode_counts(self) -> np.ndarray:
        return np.array([len(d) for d in self._returns], dtype=np.int64)

    def estimated_returns(self) -> np.ndarray:
        """J_hat: sliding-window Monte Carlo return estimate for each task.

        A task with no episodes yet is assumed to be at random-policy
        performance, which gives it the largest possible gap and therefore the
        highest sampling priority.
        """
        if self.use_success_as_return:
            return self.success_rates()

        rand = self._rand()
        return np.array(
            [float(np.mean(d)) if len(d) > 0 else rand[i] for i, d in enumerate(self._returns)],
            dtype=np.float64,
        )

    def reference_returns(self) -> np.ndarray:
        """J_ref, latching to the max observed return once a task is solvable."""
        if self.use_success_as_return:
            return np.ones(self.num_tasks, dtype=np.float64)

        self.ref_is_max_observed |= self.success_rates() > self.ref_success_threshold

        ref = np.empty(self.num_tasks, dtype=np.float64)
        for i in range(self.num_tasks):
            if self.ref_is_max_observed[i] and np.isfinite(self.return_max[i]):
                ref[i] = self.return_max[i]
            elif self.return_ref_init is not None:
                ref[i] = self.return_ref_init[i]
            else:
                # No upper bound given and nothing observed yet.
                ref[i] = self._rand()[i]
        return ref

    def normalized_gaps(self) -> np.ndarray:
        """g in [0, 1]^k, the quantity DRATS runs mirror ascent on."""
        ref = self.reference_returns()
        rand = self._rand()
        j_hat = self.estimated_returns()

        # J_ref <= J_rand means we have never seen this task do better than a
        # random policy, so the normalization is undefined and the task is as
        # far from solved as it can be. Give it the largest possible gap rather
        # than dividing by a degenerate (or negative) range.
        denom = ref - rand
        valid = denom > 1e-8
        gaps = np.where(valid, (ref - j_hat) / np.where(valid, denom, 1.0), 1.0)
        return np.clip(gaps, 0.0, 1.0)

    def learning_progress(self) -> np.ndarray:
        """|J_hat_t - J_hat_{t-1}|, the ALP-GMM / RIAC prioritization signal.

        Requires `commit()` to be called once per task-distribution update.
        """
        if self._returns_prev is None:
            return np.zeros(self.num_tasks, dtype=np.float64)
        return np.abs(self.estimated_returns() - self._returns_prev)

    def commit(self) -> None:
        """Snapshot the current estimates; call once per task-distribution update."""
        self._returns_prev = self.estimated_returns()

    def log_dict(self, prefix: str = "") -> dict:
        """Per-task scalars worth writing to evaluations.npz."""
        gaps = self.normalized_gaps()
        refs = self.reference_returns()
        j_hat = self.estimated_returns()
        out = {}
        for i in range(self.num_tasks):
            out[f"{prefix}gap_{i}"] = float(gaps[i])
            out[f"{prefix}return_ref_{i}"] = float(refs[i])
            out[f"{prefix}return_mc_{i}"] = float(j_hat[i])
        return out
